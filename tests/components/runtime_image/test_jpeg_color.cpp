struct ExpectedPixel {
  const char *name;
  int x;
  int y;
  uint8_t red;
  uint8_t green;
  uint8_t blue;
};

// Sampled at the middle of each quadrant, away from the edges where the shared chroma samples
// of neighbouring quadrants bleed into each other.
static const ExpectedPixel EXPECTED_PIXELS[] = {
    {"red", 3, 3, 0xFF, 0x00, 0x00},
    {"blue", 12, 3, 0x00, 0x00, 0xFF},
    {"green", 3, 12, 0x00, 0xFF, 0x00},
    {"yellow", 12, 12, 0xFF, 0xFF, 0x00},
};

// JPEG is lossy and the image is stored as RGB565, so exact values are not expected
static constexpr int COLOR_TOLERANCE = 24;

class JpegColorImage : public RuntimeImage {
 public:
  explicit JpegColorImage(image::ImageType type)
      : RuntimeImage(JPEG, type, image::TRANSPARENCY_OPAQUE, nullptr, false, 0, 0) {}
};

static bool decode_all(JpegColorImage &img, const uint8_t *data, size_t len) {
  std::vector<uint8_t> buffer(data, data + len);  // feed_data needs mutable bytes
  if (!img.begin_decode(len, JPEG)) {
    return false;
  }
  size_t offset = 0;
  while (offset < len) {
    int consumed = img.feed_data(buffer.data() + offset, len - offset);
    if (consumed <= 0) {
      return false;  // decode error, or no progress despite full data
    }
    offset += consumed;
  }
  img.end_decode();
  return true;
}

// A JPEG must keep its colours, rather than arriving with red and blue exchanged. JPEGDEC's
// RGB8888 output has them the wrong way round in its vectorised colour conversion, so an image
// stored as RGB565 is decoded straight to RGB565 instead. Image types that still ask for
// RGB8888 are affected on machines with NEON or SSE2, so only RGB565 is asserted here.
TEST(RuntimeImageJpegColor, DecodesSubsampledJpegWithoutSwappingChannels) {
  JpegColorImage img(image::IMAGE_TYPE_RGB565);

  ASSERT_TRUE(decode_all(img, JPEG_QUADRANTS_420, sizeof(JPEG_QUADRANTS_420)));
  ASSERT_EQ(img.get_width(), 16);
  ASSERT_EQ(img.get_height(), 16);
  for (const auto &expected : EXPECTED_PIXELS) {
    Color actual = img.get_pixel(expected.x, expected.y);
    EXPECT_NEAR(actual.red, expected.red, COLOR_TOLERANCE) << expected.name << " pixel red";
    EXPECT_NEAR(actual.green, expected.green, COLOR_TOLERANCE) << expected.name << " pixel green";
    EXPECT_NEAR(actual.blue, expected.blue, COLOR_TOLERANCE) << expected.name << " pixel blue";
  }
}

